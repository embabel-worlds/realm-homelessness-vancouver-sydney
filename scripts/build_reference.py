"""
Build the realm's reference data: homelessness in Vancouver and Sydney, from the published
counts of both cities and the census estimate Australia makes, reduced to one figure per row.

Sources (all in data/source/, git-ignored; scripts/fetch_sources.sh downloads them):

  Vancouver
    hsabc     HSABC Greater Vancouver point-in-time count, 2005–2025. PDF only, so the figures
              are transcribed in data/curated/hsabc-greater-vancouver.yml with table citations.
    bcstats   BC Stats annual estimate (anyone seen in shelter or on income assistance with no
              fixed address during the year), 2019–2024, by census division. CSV.
    hicc      Statistics Canada 14-10-0353, shelter beds by type, City of Vancouver, 2016–2025. CSV.
    population  StatCan 17-10-0148 (Vancouver CMA, July estimates) and 98-10-0002 (City of
              Vancouver, census 2016 and 2021).

  Sydney
    cos       City of Sydney street count, Feb and Aug 2010–2021, Feb 2022–2026. An HTML table.
    nsw       NSW Statewide Street Count, 2020–2026, every LGA counted. PDF technical paper,
              parsed with PyMuPDF; the parse is checked against the paper's own NSW totals.
    abs       ABS Estimating Homelessness: Census 2021 (2049.0) data cubes — City of Sydney LGA
              (2016, 2021), Greater Sydney (2021), NSW by usual residence (2006–2021). XLSX.
    population  ABS ERP for City of Sydney LGA and Greater Sydney, 2001–2025. CSV.

The two cities do not count the same thing, and the realm never pretends they do. Every
figure carries its source's `tier` (what kind of count it is) and, only where the meaning
genuinely lines up, a `compareAs` family:

  sleepingOutside       Vancouver PiT unsheltered | Sydney street-count rough sleepers | ABS
                        improvised dwellings / sleeping out. Vancouver's figure also includes
                        couch-surfers (17% of it in 2025), so it reads high against Sydney's.
  inCrisisAccommodation Vancouver PiT sheltered | City of Sydney occupied crisis and temporary
                        beds | ABS supported accommodation for the homeless.
  oneNightTotal         Vancouver PiT total | City of Sydney rough sleepers + occupied beds
                        (derived here, flagged `derived`).

Rates per 10,000 use the population of the same place in the nearest year held; the year used
is stored beside the rate so nobody mistakes it for a matched denominator.

Run from the realm root:  python3 scripts/build_reference.py
"""
