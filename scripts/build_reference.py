def build_hsabc():
    c = yaml.safe_load((CURATED / "hsabc-greater-vancouver.yml").read_text())
    couch = c["unshelteredCouchSurfingShare2025"]
    for year, r in c["regional"].items():
        for m in ("total", "sheltered", "unsheltered"):
            note = f"{couch}% of the 2025 unsheltered stayed with others (couch-surfing)." if (m == "unsheltered" and year == 2025) else None
            figure("hsabc-pit", "van-metro", year, m, r[m], period=f"{year}-03", note=note)
    years = c["subregionYears"]
    for sub, vals in c["subregionTotals"].items():
        if sub == "Unspecified":
            continue
        pid = "van-city" if sub == "Vancouver" else "van-" + re.sub(r"[^a-z]+", "-", sub.lower()).strip("-")
        for year, v in zip(years, vals):
            figure("hsabc-pit", pid, year, "total", v, period=f"{year}-03")
    for sub, r in c["subregions2025"].items():
        pid = "van-city" if sub == "Vancouver" else "van-" + re.sub(r"[^a-z]+", "-", sub.lower()).strip("-")
        figure("hsabc-pit", pid, 2025, "unsheltered", r["unsheltered"], period="2025-03")
        figure("hsabc-pit", pid, 2025, "sheltered", r["sheltered"], period="2025-03")
        figure("hsabc-pit", pid, 2025, "shelteredShelters", r["shelters"], period="2025-03")
        figure("hsabc-pit", pid, 2025, "shelteredExtremeWeather", r["ewr"], period="2025-03")
        figure("hsabc-pit", pid, 2025, "shelteredNoFixedAddress", r["nfa"], period="2025-03")
    s = c["regional2025Split"]
    figure("hsabc-pit", "van-metro", 2025, "shelteredShelters", s["shelters"], period="2025-03")
    figure("hsabc-pit", "van-metro", 2025, "shelteredExtremeWeather", s["ewr"], period="2025-03")
    figure("hsabc-pit", "van-metro", 2025, "shelteredNoFixedAddress", s["nfa"], period="2025-03")
    for sub, v in c["subregionUnsheltered2023"].items():
        pid = "van-city" if sub == "Vancouver" else "van-" + re.sub(r"[^a-z]+", "-", sub.lower()).strip("-")
        figure("hsabc-pit", pid, 2023, "unsheltered", v, period="2023-03")
        total = dict(zip(years, c["subregionTotals"][sub]))[2023]
        figure("hsabc-pit", pid, 2023, "sheltered", total - v, period="2023-03", derived=True,
               note="Total minus unsheltered (Tables 2 and 4).")
    for m, r in c["demographics2025"].items():
        figure("hsabc-pit", "van-metro", 2025, m, r["value"], period="2025-03", unit="respondents",
               respondents=r["respondents"], share=round(100 * r["value"] / r["respondents"], 1),
               note="Of survey respondents who answered, not of everyone counted.")


