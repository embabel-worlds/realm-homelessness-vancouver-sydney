def attach_rates(pops):
    by_place = {}
    for p in pops:
        by_place.setdefault(p["placeId"], []).append(p)
    for f in figures:
        cands = by_place.get(f["placeId"])
        # A subgroup (Indigenous, an age band) over the whole population is not a rate anyone publishes.
        if not cands or f["unit"] != "persons" or f["measure"] in SUBGROUPS:
            continue
        best = min(cands, key=lambda p: (abs(p["year"] - f["year"]), -p["year"]))
        f["population"] = best["population"]
        f["populationYear"] = best["year"]
        f["per10k"] = round(10000 * f["value"] / best["population"], 1)


def write(name, records):
    out = REFERENCE / name
    with out.open("w") as fh:
        fh.write(HEADER)
        yaml.safe_dump(records, fh, sort_keys=False, allow_unicode=True, width=1000)
    print(f"{out.relative_to(ROOT)}: {len(records)}")


