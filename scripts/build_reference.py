def _table_rows(path):
    """Every <tr> of the page's first table, as cell texts. html5lib, not a hand parser: the
    City's markup drops the <tr> before August 2016, and only the HTML5 tree-builder repairs
    that the way a browser does (the row is on the page people read)."""
    doc = html5lib.parse(path.read_text(), namespaceHTMLElements=False)
    table = doc.find(".//table")
    return [["".join(c.itertext()).strip() for c in tr if c.tag in ("td", "th")] for tr in table.iter("tr")]


MONTHS = {"February": "02", "August": "08"}


def build_cos():
    n = 0
    for r in _table_rows(SOURCE / "cos_streetcounts.html"):
        if len(r) == 3 and re.match(r"^(February|August) \d{4}$", r[0]):
            month, year = r[0].split()
            period = f"{year}-{MONTHS[month]}"
            rough, beds = int(r[1].replace(",", "")), int(r[2].replace(",", ""))
            figure("cos-street-count", "syd-city", year, "roughSleeping", rough, period=period)
            figure("cos-street-count", "syd-city", year, "occupiedCrisisBeds", beds, period=period)
            figure("cos-street-count", "syd-city", year, "roughSleepingPlusOccupiedBeds", rough + beds,
                   period=period, derived=True, note="Sum of the two published figures.")
            n += 1
    if n < 27:
        sys.exit(f"City of Sydney table: expected at least 27 counts, parsed {n}")


def build_nsw(places):
    doc = pymupdf.open(SOURCE / "nsw_streetcount_2026_tp.pdf")
    lines = [l.strip() for p in doc for l in p.get_text().splitlines()]
    start = next(i for i, l in enumerate(lines) if l.startswith("Appendix A"))
    end = next(i for i in range(start, len(lines)) if lines[i].startswith("Appendix B"))
    cells = [l for l in lines[start:end] if l]
    years = list(range(2020, 2027))
    number = re.compile(r"^(\d[\d,]*)\*?$")

    # The paper's own statewide row is the check on the parse below.
    i = cells.index("NSW Totals")
    nsw_totals = [int(c.replace(",", "")) for c in cells[i + 2:i + 9]]

    # Each LGA is: name (may wrap, and the first LGA of a district group is preceded by the
    # group's name), the count date ("23 February" / "2026"), scheduled locations, then 2020–2026.
    date = re.compile(r"^\d{1,2}\s+(February|March)$")
    stop = {"results", "2026", "Total", "2026 street", "NSW Totals"}
    sums = [0] * len(years)
    k = 0
    while k < len(cells):
        if date.match(cells[k]) and k + 1 < len(cells) and cells[k + 1] == "2026":
            j, parts = k - 1, []
            while j >= 0 and not number.match(cells[j]) and cells[j] not in stop and cells[j] != "Not counted" \
                    and not cells[j].startswith("Technical Paper"):
                parts.insert(0, cells[j])
                j -= 1
            joined = ""
            for p in parts:
                joined += p if joined.endswith(("‑", "–", "-")) else (" " + p if joined else p)
            joined = joined.replace("‑", "-").replace("–", "-")
            group = next((g for g in NSW_DISTRICT_GROUPS if joined.startswith(g + " ")), None)
            lga = joined[len(group) + 1:] if group else joined
            lga = WRAPPED_NAMES.get(lga, lga)
            vals = cells[k + 3:k + 3 + len(years)]
            pid = "nsw-" + re.sub(r"[^a-z]+", "-", lga.lower()).strip("-")
            if lga != "City of Sydney":
                places.append(place(pid, lga, "Sydney", "lga", f"{lga} local government area, NSW.",
                                    parent="syd-metro" if lga in GREATER_SYDNEY_LGAS else "nsw",
                                    inGreaterSydney=lga in GREATER_SYDNEY_LGAS))
            for y, v in zip(years, vals):
                m = number.match(v)
                if m:
                    sums[y - 2020] += int(m.group(1).replace(",", ""))
                    if lga != "City of Sydney":
                        figure("nsw-street-count", pid, y, "roughSleeping", int(m.group(1).replace(",", "")),
                               note="Asterisked in the source." if v.endswith("*") else None)
            k += 3 + len(years)
        else:
            k += 1
    # The 2026 paper lists only LGAs still counted, so for earlier years its LGA rows fall short of
    # its own NSW totals (Parkes, last counted in 2025, is one). From 2024 the sum must be exact;
    # before that the published total is stored and the shortfall recorded on it.
    for y, got, want in zip(years, sums, nsw_totals):
        if got > want or (y >= 2024 and got != want):
            sys.exit(f"NSW street count {y}: LGA rows sum to {got}, the paper's NSW total is {want}")
    for y, v, got in zip(years, nsw_totals, sums):
        figure("nsw-street-count", "nsw", y, "roughSleeping", v,
               note=f"{v - got} counted in LGAs the 2026 paper no longer lists." if v != got else None)


def _rows(path, sheet):
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    return [[c for c in r if c is not None] for r in wb[sheet].iter_rows(values_only=True)]


