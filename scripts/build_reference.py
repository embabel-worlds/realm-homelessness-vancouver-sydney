def place(placeId, name, city, scale, description, parent=None, country=None, **extra):
    PLACE_CITY[placeId] = city
    p = dict(placeId=placeId, name=name, city=city, country=country or ("Canada" if city == "Vancouver" else "Australia"),
             scale=scale, description=description)
    if parent:
        p["parent"] = parent
    p.update(extra)
    return p


figures = []


def figure(sourceId, placeId, year, measure, value, period=None, unit="persons", **extra):
    if value is None:
        return
    label, compare = MEASURES[measure]
    compare = COMPARE_BY_SOURCE.get((sourceId, measure), compare)
    period = period or str(year)
    f = dict(figureId=f"{sourceId}:{placeId}:{period}:{measure}", sourceId=sourceId, placeId=placeId,
             city=PLACE_CITY[placeId], tier=SOURCE_TIER[sourceId], year=int(year), period=period,
             measure=measure, measureLabel=label, value=int(value), unit=unit)
    if compare and unit == "persons":
        f["compareAs"] = compare
    f.update({k: v for k, v in extra.items() if v is not None})
    figures.append(f)


