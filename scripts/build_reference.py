def sydney_population():
    pops = []
    for f, pid, name in (("abs_erp_lga2025_cityofsydney.csv", "syd-city", "City of Sydney LGA (2025 boundaries)"),
                         ("abs_erp_gccsa_greatersydney.csv", "syd-metro", "Greater Sydney GCCSA")):
        with open(SOURCE / f, newline="") as fh:
            for r in csv.DictReader(fh):
                pops.append(dict(placeId=pid, year=int(r["TIME_PERIOD"]), population=int(r["OBS_VALUE"]),
                                 kind="estimate", source=f"ABS estimated resident population, {name}, 30 June"))
    return pops


